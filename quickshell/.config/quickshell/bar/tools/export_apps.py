#!/usr/bin/env python3
"""Write the active Quickshell theme into apps that can reload it live.
Called by ThemeExport.qml on every theme switch:  export_apps.py '<json>'
json = { "name": ..., "palette": {roles...}, "termBg": "#rrggbb", "options": {"obsidian":true,...} }

Mechanisms (each one was checked against the app's docs or source):
  Obsidian  CSS snippet in every vault; Obsidian hot-reloads snippet files.
  OBS       Yami variant theme (.ovt); live when [Appearance] AutoReload=true in user.ini.
  AyuGram   .tdesktop-theme colors file; Telegram Desktop watches the loaded theme file (QFileSystemWatcher).
  Brave     BrowserThemeColor policy + `brave --refresh-platform-policy` (needs setup_apps.py --brave once).
"""
import colorsys, json, os, pathlib, re, shutil, subprocess, sys

HOME = pathlib.Path(os.environ.get("HOME", "~")).expanduser()
HERE = pathlib.Path(__file__).resolve().parent

# ── color helpers ──────────────────────────────────────────────────────
def rgb(h):  return [int(h[i:i + 2], 16) for i in (1, 3, 5)]
def hexs(c): return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)
def mix(a, b, t):
    x, y = rgb(a), rgb(b)
    return hexs([x[i] * (1 - t) + y[i] * t for i in range(3)])
def to_hls(h):
    r, g, b = [v / 255 for v in rgb(h)]
    H, L, S = colorsys.rgb_to_hls(r, g, b)
    return H * 360, L, S
def from_hls(H, L, S):
    r, g, b = colorsys.hls_to_rgb((H % 360) / 360, max(0, min(1, L)), max(0, min(1, S)))
    return hexs([r * 255, g * 255, b * 255])

def write_inplace(path, text):
    """Truncate-and-write (same inode) so apps that watch the file keep watching it."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf8") as f:
        f.write(text)

# ── Obsidian ───────────────────────────────────────────────────────────
def obsidian(p, opts):
    def rgbs(h): return ", ".join(str(v) for v in rgb(h))
    css = [f"/* generated by Quickshell ({opts['name']}) - do not edit */",
           "body, body.theme-dark, body.theme-light, .theme-dark, .theme-light {"]
    v = {
        "--background-primary": p["termBg"], "--background-primary-alt": p["mantle"],
        "--background-secondary": p["mantle"], "--background-secondary-alt": p["base"],
        "--background-modifier-border": p["surface0"], "--background-modifier-border-hover": p["selected"],
        "--background-modifier-border-focus": p["accent"],
        "--text-normal": p["text"], "--text-muted": p["subtext"], "--text-faint": mix(p["subtext"], p["termBg"], 0.45),
        "--text-on-accent": p["base"], "--text-accent": p["accent"], "--text-accent-hover": mix(p["accent"], p["text"], 0.25),
        "--text-success": p["green"], "--text-warning": p["yellow"], "--text-error": p["red"],
        "--text-selection": mix(p["accent"], p["termBg"], 0.7),
        "--interactive-normal": p["surface0"], "--interactive-hover": p["selected"],
        "--interactive-accent": p["accent"], "--interactive-accent-hover": mix(p["accent"], p["text"], 0.2),
        "--color-accent": p["accent"], "--color-accent-1": p["accent"], "--color-accent-2": mix(p["accent"], p["termBg"], 0.3),
        "--color-red": p["red"], "--color-orange": p["peach"], "--color-yellow": p["yellow"],
        "--color-green": p["green"], "--color-cyan": p["teal"], "--color-blue": p["blue"],
        "--color-purple": p["accent"], "--color-pink": p["red"],
        "--color-base-00": p["base"], "--color-base-10": p["mantle"], "--color-base-20": p["termBg"],
        "--color-base-25": p["surface0"], "--color-base-30": p["selected"],
    }
    for k, val in v.items():
        css.append(f"  {k}: {val};")
    for name in ("red", "orange", "yellow", "green", "cyan", "blue", "purple", "pink"):
        css.append(f"  --color-{name}-rgb: {rgbs(v['--color-' + name])};")
    css.append(f"  --color-accent-rgb: {rgbs(p['accent'])};")
    css.append("}\n")
    text = "\n".join(css)

    vaults = []
    cfg = HOME / ".config" / "obsidian" / "obsidian.json"
    try:
        for entry in json.loads(cfg.read_text(encoding="utf8")).get("vaults", {}).values():
            if entry.get("path"):
                vaults.append(pathlib.Path(entry["path"]))
    except Exception:
        pass
    vaults += [pathlib.Path(x).expanduser() for x in opts.get("obsidianVaults", [])]
    done = 0
    for vault in dict.fromkeys(vaults):
        if (vault / ".obsidian").is_dir():
            write_inplace(vault / ".obsidian" / "snippets" / "qs-theme.css", text)
            done += 1
    return f"obsidian: {done} vault(s)"

# ── OBS Studio ─────────────────────────────────────────────────────────
def steps(c, bg):
    return [c] + [mix(c, bg, t) for t in (0.12, 0.30, 0.45, 0.60, 0.75)]

def obs(p, opts):
    base = HOME / ".config" / "obs-studio"
    if not base.is_dir():
        return "obs: ~/.config/obs-studio not found, skipped"
    bg = p["termBg"]
    g = {8: p["base"], 7: p["mantle"], 6: bg, 5: p["surface0"], 4: mix(p["surface0"], p["selected"], 0.5),
         3: p["selected"], 2: mix(p["selected"], p["subtext"], 0.30), 1: mix(p["selected"], p["subtext"], 0.55)}
    var = {f"--grey{i}": g[i] for i in range(1, 9)}
    var.update({
        "--primary": mix(p["accent"], bg, 0.45), "--primary_light": mix(p["accent"], bg, 0.30),
        "--primary_lighter": p["accent"], "--primary_dark": mix(p["accent"], bg, 0.60),
        "--primary_darker": mix(p["accent"], bg, 0.75),
        "--text": p["text"], "--text_light": p["selectedText"], "--text_muted": p["subtext"],
    })
    for name, col in (("blue", p["blue"]), ("red", p["red"]), ("green", p["green"]),
                      ("yellow", p["yellow"]), ("purple", p["accent"])):
        for i, c in enumerate(steps(col, bg), 1):
            var[f"--{name}{i}"] = c
    lines = ["/* generated by Quickshell - do not edit */", "@OBSThemeMeta {", "    name: 'Quickshell';",
             "    id: 'com.quickshell.Yami';", "    extends: 'com.obsproject.Yami';",
             "    author: 'Quickshell';", "    dark: 'true';", "}", "", "@OBSThemeVars {"]
    lines += [f"    {k}: {v};" for k, v in var.items()]
    lines += ["}", ""]
    write_inplace(base / "themes" / "Yami_Quickshell.ovt", "\n".join(lines))
    return "obs: Yami_Quickshell.ovt written"

# ── AyuGram / Telegram Desktop ─────────────────────────────────────────
TG_BASE = HERE / "tdesktop-night-base.txt"     # Telegram's own night-custom-base colors file

def tg_ramp(p):
    """(source lightness -> palette color) stops, anchored on colors Telegram's night theme really uses."""
    L = lambda h: to_hls(h)[1]
    return [(0.0, mix(p["base"], "#000000", 0.35)),
            (L("#0e1621"), p["base"]),            # darkest bluish background
            (L("#17212b"), p["termBg"]),          # windowBg
            (L("#232e3c"), p["surface0"]),        # windowBgOver
            (L("#2b5278"), p["selected"]),
            (L("#708499"), p["subtext"]),         # windowSubTextFg
            (L("#c6ccd3"), mix(p["subtext"], p["text"], 0.55)),
            (L("#f5f5f5"), p["text"]),            # windowFg
            (1.0, p["selectedText"])]

def tg_family(H, p):
    if H >= 335 or H < 25:  return p["red"]
    if H < 45:              return p["peach"]
    if H < 70:              return p["yellow"]
    if H < 170:             return p["green"]
    return p["accent"]                              # blues, teals, purples, pinks -> the accent

def tg_remap(h, p, ramp):
    H, L, S = to_hls(h)
    if L > 0.995 or L < 0.004:                      # pure white / pure black stay
        return h
    if S < 0.07 and 0.04 < L < 0.9 or (S < 0.36 and 185 <= H <= 255):   # neutrals and blue-greys
        for (l0, c0), (l1, c1) in zip(ramp, ramp[1:]):
            if L <= l1:
                t = 0 if l1 == l0 else (L - l0) / (l1 - l0)
                return mix(c0, c1, t)
        return ramp[-1][1]
    if S < 0.07:                                    # light neutrals (text)
        return p["text"]
    tH, tL, tS = to_hls(tg_family(H, p))
    return from_hls(tH, L, min(0.9, tS * 0.7))

def ayugram(p, opts):
    if not TG_BASE.exists():
        return "ayugram: tools/tdesktop-night-base.txt missing"
    ramp = tg_ramp(p)
    def sub(m):
        lit = m.group(0)
        rgb6, alpha = lit[:7], lit[7:]
        return tg_remap(rgb6, p, ramp) + alpha
    out = re.sub(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", sub, TG_BASE.read_text(encoding="utf8"))
    out = f"// generated by Quickshell ({opts['name']}) from Telegram's night-custom-base theme\n" + out
    write_inplace(HOME / ".local" / "share" / "quickshell-bar" / "telegram.tdesktop-theme", out)
    return "ayugram: telegram.tdesktop-theme written"

# ── Brave ──────────────────────────────────────────────────────────────
def brave(p, opts):
    helper = pathlib.Path("/usr/local/bin/qs-brave-policy")
    if not helper.exists():
        return "brave: not set up (run: python3 setup_apps.py --brave)"
    col = p["termBg"].lstrip("#").lower()
    r = subprocess.run(["sudo", "-n", str(helper), col], capture_output=True, text=True)
    if r.returncode != 0:
        return "brave: policy write failed (sudo rule missing?)"
    exe = shutil.which("brave") or shutil.which("brave-browser")
    running = subprocess.run(["pgrep", "-x", "brave"], capture_output=True).returncode == 0
    if exe and running:
        subprocess.Popen([exe, "--refresh-platform-policy", "--no-startup-window"],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    return "brave: policy updated" + (" and refreshed" if exe and running else "")

def main():
    data = json.loads(sys.argv[1])
    p = dict(data["palette"]); p["termBg"] = data["termBg"]
    o = data.get("options", {}); o["name"] = data.get("name", "")
    for key, fn in (("obsidian", obsidian), ("obs", obs), ("ayugram", ayugram), ("brave", brave)):
        if o.get(key, True):
            try:
                print(fn(p, o))
            except Exception as e:
                print(f"{key}: failed ({e})")

if __name__ == "__main__":
    main()
